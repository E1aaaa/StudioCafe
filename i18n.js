const DEFAULT_LANG = "en";

function cookiesAccepted() {
    return localStorage.getItem("cookieConsent") === "accepted";
}

function getInitialLang() {
    const saved = sessionStorage.getItem("lang") || (cookiesAccepted() ? localStorage.getItem("lang") : null);
    if (saved && translations[saved]) return saved;

    const browserLang = (navigator.language || "").toLowerCase();
    if (browserLang.startsWith("mk")) return "mk";
    if (browserLang.startsWith("sq")) return "sq";
    if (browserLang.startsWith("tr")) return "tr";
    return DEFAULT_LANG;
}

function setLanguage(lang) {
    if (!translations[lang]) lang = DEFAULT_LANG;
    const dict = translations[lang];

    document.documentElement.lang = lang;
    sessionStorage.setItem("lang", lang);
    if (cookiesAccepted()) localStorage.setItem("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key] !== undefined) el.textContent = dict[key];
    });

    document.querySelectorAll("[data-i18n-html]").forEach(el => {
        const key = el.getAttribute("data-i18n-html");
        if (dict[key] !== undefined) el.innerHTML = dict[key];
    });

    document.querySelectorAll("[data-i18n-alt]").forEach(el => {
        const key = el.getAttribute("data-i18n-alt");
        if (dict[key] !== undefined) el.setAttribute("alt", dict[key]);
    });

    document.querySelectorAll("[data-i18n-content]").forEach(el => {
        const key = el.getAttribute("data-i18n-content");
        if (dict[key] !== undefined) el.setAttribute("content", dict[key]);
    });

    document.querySelectorAll(".lang-btn").forEach(btn => {
        btn.classList.toggle("active", btn.dataset.lang === lang);
    });
}

document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
});

